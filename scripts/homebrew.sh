#!/usr/bin/env bash
# The Homebrew cask for a release, from its checksums.txt, for the tap
# stagdhq/homebrew-tap (Casks/stagd.rb): brew install stagdhq/tap/stagd.
# The release workflow runs it.
#
#   scripts/homebrew.sh v0.4.0 dist/checksums.txt > Casks/stagd.rb
#
# A cask, not a formula: a formula without a bottle counts as built from
# source, so Homebrew first insists on current Xcode Command Line Tools,
# though stagd is already built; casks skip that. A third argument replaces
# where the archives are downloaded from, e.g. a file:// folder to try the
# cask before a release.
set -euo pipefail

tag="$1"
sums="$2"
base="${3:-https://github.com/stagdhq/stagd/releases/download/$tag}"

sum() {
  awk -v f="stagd_$1.tar.gz" '$2 == f { print $1 }' "$sums"
}

for target in darwin_arm64 darwin_amd64 linux_arm64 linux_amd64; do
  [ -n "$(sum "$target")" ] || { echo "no stagd_$target.tar.gz in $sums" >&2; exit 1; }
done

cat <<RUBY
# Generated by stagd's release workflow (scripts/homebrew.sh); don't edit it by hand.
cask "stagd" do
  version "${tag#v}"

  on_macos do
    on_arm do
      sha256 "$(sum darwin_arm64)"
      url "$base/stagd_darwin_arm64.tar.gz"
    end

    on_intel do
      sha256 "$(sum darwin_amd64)"
      url "$base/stagd_darwin_amd64.tar.gz"
    end
  end
  on_linux do
    on_arm do
      sha256 "$(sum linux_arm64)"
      url "$base/stagd_linux_arm64.tar.gz"
    end

    on_intel do
      sha256 "$(sum linux_amd64)"
      url "$base/stagd_linux_amd64.tar.gz"
    end
  end

  name "stagd"
  desc "Live, seeded preview environments for every pull request"
  homepage "https://stagd.dev/"

  livecheck do
    url :url
    strategy :github_latest
  end

  binary "stagd"

  # stagd isn't notarised yet: without this, Gatekeeper may stop the
  # downloaded binary on macOS. A postflight block, not postflight_steps
  # (Homebrew 6 and later), so Homebrew from 4.5 on reads the cask.
  postflight do
    if OS.mac?
      system_command "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "#{staged_path}/stagd"]
    end
  end
end
RUBY
