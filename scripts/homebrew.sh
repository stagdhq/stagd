#!/usr/bin/env bash
# The Homebrew formula for a release, from its checksums.txt, for the tap
# stagdhq/homebrew-tap (Formula/stagd.rb). The release workflow runs it.
#
#   scripts/homebrew.sh v0.3.0 dist/checksums.txt > Formula/stagd.rb
#
# A third argument replaces where the archives are downloaded from, e.g. a
# file:// folder to try the formula before a release.
set -euo pipefail

tag="$1"
sums="$2"
base="${3:-https://github.com/stagdhq/stagd/releases/download/$tag}"

sum() {
  awk -v f="stagd_$1.tar.gz" '$2 == f { print $1 }' "$sums"
}

for target in darwin_arm64 darwin_amd64 linux_arm64 linux_amd64; do
  [ -n "$(sum "$target")" ] || { echo "no stagd_$target.tar.gz in $sums" >&2; exit 1; }
done

cat <<RUBY
# Generated by stagd's release workflow (scripts/homebrew.sh); don't edit it by hand.
class Stagd < Formula
  desc "Live, seeded preview environments for every pull request"
  homepage "https://stagd.dev"
  version "${tag#v}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/stagd_darwin_arm64.tar.gz"
      sha256 "$(sum darwin_arm64)"
    end

    on_intel do
      url "$base/stagd_darwin_amd64.tar.gz"
      sha256 "$(sum darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$base/stagd_linux_arm64.tar.gz"
      sha256 "$(sum linux_arm64)"
    end

    on_intel do
      url "$base/stagd_linux_amd64.tar.gz"
      sha256 "$(sum linux_amd64)"
    end
  end

  def install
    bin.install "stagd"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/stagd --version")
  end
end
RUBY
